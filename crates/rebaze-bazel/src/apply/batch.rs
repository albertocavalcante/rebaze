//! Opt-in complete staging and forward recovery for existing parent directories.

use std::io;
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};

use super::fs::{Directory, Identity};
use super::guard::Guard;
use super::{
    ApplyError, FileEditPlan, Journal, Manifest, MetadataPolicy, Point, RecordKind, RestoreRecord,
    archive_directory, manifest_digest, pending_record, restore_entry, stage_file,
    validate_journal,
};
use crate::{OutputBundle, OutputPath};

const MAX_FILES: usize = 128;
const MAX_OUTPUT_BYTES: u64 = 64 * 1024 * 1024;
const MAX_BASELINE_BYTES: u64 = 128 * 1024 * 1024;
const MAX_INTENT_BYTES: u64 = 2 * 1024 * 1024;
const BATCH_SCHEMA: u32 = 1;
// Older single-file readers must take their strict decoder's error path rather
// than interpreting missing single-file intent as an abandoned batch.
const COMPATIBILITY_MARKER: &[u8] = b"{\"batch_protocol\":1}\n";

/// A sealed batch of file observations and owned generated bytes.
#[derive(Debug)]
pub struct BatchEditPlan {
    files: Vec<FileEditPlan>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BatchOutcome {
    Applied,
    /// Preparation stopped before publication; no baseline claim is available.
    Unprepared,
    /// Every destination was observed to match its captured baseline.
    BaselineVerified,
    /// Intervening changes were preserved; some outputs may already be applied.
    Conflict,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ConflictReason {
    DestinationChanged,
    NonRegularDestination,
    MovedEntryChanged,
    MissingStage,
    MissingDestination,
    MissingBackup,
    RestorationObserved,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum OutputDisposition {
    Applied,
    Baseline,
    Conflict(ConflictReason),
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OutputReport {
    pub path: OutputPath,
    pub disposition: OutputDisposition,
}

/// Sequential terminal observations, not an observer-atomic snapshot.
#[derive(Debug, Clone, PartialEq, Eq)]
#[must_use = "inspect the batch outcome and per-output evidence before claiming application success"]
pub struct BatchReceipt {
    pub outcome: BatchOutcome,
    pub outputs: Vec<OutputReport>,
    pub retained: PathBuf,
}

#[derive(Debug, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct Preparation {
    schema: u32,
    transaction: Identity,
    plans: Vec<Manifest>,
    identity: [u8; 32],
}

#[derive(Debug, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct CompleteIntent {
    schema: u32,
    transaction: Identity,
    preparation: [u8; 32],
    entries: Vec<Journal>,
    identity: [u8; 32],
}

#[derive(Debug, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct StopRecord {
    identity: [u8; 32],
    reason: ConflictReason,
}

#[derive(Debug, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct DoneRecord {
    identity: [u8; 32],
    plan_identity: [u8; 32],
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum Phase {
    CompatibilityRecord(super::fs::RecordPoint),
    PreparationRecord(super::fs::RecordPoint),
    StageStarted,
    StageSync,
    StageDirectorySync,
    IntentRecord(super::fs::RecordPoint),
    IntentDurable,
    BaselineChecked,
    Moved,
    BeforeInstall,
    InstallSync,
    Installed,
    DoneRecord(super::fs::RecordPoint),
    StopRecord(super::fs::RecordPoint),
    RestoreRecord(super::fs::RecordPoint),
    BeforeRestore,
    RestoreSync,
    ReconcileSync,
}

impl BatchEditPlan {
    /// Observe a nonempty bundle without writes. All parent directories must exist.
    ///
    /// This profile accepts at most 128 files, 64 MiB intended bytes and 128 MiB
    /// captured baseline bytes, subject to each single-file limit as well.
    ///
    /// ```
    /// use rebaze_bazel::{OutputBundle, apply::{BatchEditPlan, BatchOutcome, MetadataPolicy, recover_bundle}};
    /// let root = tempfile::tempdir()?;
    /// let bundle = OutputBundle::new([
    ///     ("BUILD.bazel".to_owned(), "# generated\n".to_owned()),
    ///     ("defs.bzl".to_owned(), "# helpers\n".to_owned()),
    /// ])?;
    /// let receipt = BatchEditPlan::capture(root.path(), bundle, MetadataPolicy::PosixModeAndOwner)?.apply()?;
    /// assert_eq!(receipt.outcome, BatchOutcome::Applied);
    /// assert_eq!(receipt.outputs.len(), 2);
    /// assert!(recover_bundle(root.path())?.is_none());
    /// # Ok::<(), Box<dyn std::error::Error>>(())
    /// ```
    pub fn capture(
        root: &Path,
        bundle: OutputBundle,
        metadata: MetadataPolicy,
    ) -> Result<Self, ApplyError> {
        if bundle.len() > MAX_FILES {
            return Err(ApplyError::Invalid("batch exceeds 128 files"));
        }
        let total = bundle
            .iter()
            .try_fold(0_u64, |total, (_, content)| {
                total.checked_add(content.len() as u64)
            })
            .ok_or(ApplyError::Invalid("batch output byte count overflow"))?;
        if total > MAX_OUTPUT_BYTES {
            return Err(ApplyError::Invalid("batch exceeds 64 MiB intended bytes"));
        }
        let mut files = Vec::with_capacity(bundle.len());
        let mut baseline_bytes = 0_u64;
        for (path, content) in bundle {
            let file = FileEditPlan::capture(root, &path, content, metadata).map_err(|source| {
                ApplyError::Output {
                    path,
                    source: Box::new(source),
                }
            })?;
            baseline_bytes = baseline_bytes
                .checked_add(
                    file.manifest
                        .expected
                        .as_ref()
                        .map_or(0, |value| value.length),
                )
                .ok_or(ApplyError::Invalid("batch baseline byte count overflow"))?;
            if baseline_bytes > MAX_BASELINE_BYTES {
                return Err(ApplyError::Invalid("batch exceeds 128 MiB baseline bytes"));
            }
            if files.first().is_some_and(|first: &FileEditPlan| {
                first.manifest.root != file.manifest.root
                    || first.manifest.root_identity != file.manifest.root_identity
            }) {
                return Err(ApplyError::Invalid("root changed during batch capture"));
            }
            files.push(file);
        }
        Ok(Self { files })
    }

    pub fn apply(self) -> Result<BatchReceipt, ApplyError> {
        self.apply_with(&mut |_| Ok(()))
    }

    fn apply_with(
        self,
        hook: &mut impl FnMut(Point) -> io::Result<()>,
    ) -> Result<BatchReceipt, ApplyError> {
        let first = self
            .files
            .first()
            .ok_or(ApplyError::Invalid("batch is empty"))?;
        let guard = Guard::open_with(&first.manifest.root, Some(&first.manifest), hook)?;
        if guard.io(guard.directory.exists("active"))? {
            return Err(guard.conflict("pending transaction requires recovery"));
        }
        for file in &self.files {
            let (parent, name) = guard.parent(&file.manifest)?;
            if guard.io(parent.fingerprint(name))? != file.manifest.expected {
                return Err(guard.conflict("batch destination changed after capture"));
            }
        }
        let active = guard.io(guard.directory.make_child("active"))?;
        guard.io(
            active.record("manifest.json", COMPATIBILITY_MARKER, &mut |point| {
                hook(Point::Batch {
                    file: None,
                    phase: Phase::CompatibilityRecord(point),
                })
            }),
        )?;
        let mut preparation = Preparation {
            schema: BATCH_SCHEMA,
            transaction: guard.io(active.identity())?,
            plans: self
                .files
                .iter()
                .map(|file| file.manifest.clone())
                .collect(),
            identity: [0; 32],
        };
        preparation.identity = preparation_identity(&preparation)?;
        let bytes = encode(&preparation)?;
        guard.io(active.record_with_limit(
            "batch-plan.json",
            &bytes,
            MAX_INTENT_BYTES,
            &mut |point| {
                hook(Point::Batch {
                    file: None,
                    phase: Phase::PreparationRecord(point),
                })
            },
        ))?;
        let entries_directory = guard.io(active.make_child("entries"))?;
        let mut entries = Vec::with_capacity(self.files.len());
        for (index, file) in self.files.into_iter().enumerate() {
            let path = output_path(&guard, &file.manifest.path)?;
            let result = (|| {
                let directory = guard.io(entries_directory.make_child(&entry_name(index)))?;
                emit(&guard, hook, Some(index), Phase::StageStarted)?;
                let staged = stage_file(
                    &guard,
                    &directory,
                    &file.manifest,
                    file.content.as_bytes(),
                    &mut file_hook(index, hook),
                )?;
                emit(&guard, hook, Some(index), Phase::StageDirectorySync)?;
                guard.io(directory.sync())?;
                Ok(Journal {
                    plan_identity: manifest_digest(&file.manifest)?,
                    plan: file.manifest,
                    transaction: guard.io(directory.identity())?,
                    staged,
                })
            })();
            entries.push(at_path(&path, result)?);
        }
        let mut complete = CompleteIntent {
            schema: BATCH_SCHEMA,
            transaction: preparation.transaction,
            preparation: preparation.identity,
            entries,
            identity: [0; 32],
        };
        complete.identity = complete_identity(&complete)?;
        guard.io(active.record_with_limit(
            "batch.json",
            &encode(&complete)?,
            MAX_INTENT_BYTES,
            &mut |point| {
                hook(Point::Batch {
                    file: None,
                    phase: Phase::IntentRecord(point),
                })
            },
        ))?;
        emit(&guard, hook, None, Phase::IntentDurable)?;
        resume(&guard, &active, &preparation, &complete, hook)
    }
}

/// Recover batch intent explicitly. Legacy single-file journals use `recover`.
pub fn recover_bundle(root: &Path) -> Result<Option<BatchReceipt>, ApplyError> {
    recover_with(root, &mut |_| Ok(()))
}

fn recover_with(
    root: &Path,
    hook: &mut impl FnMut(Point) -> io::Result<()>,
) -> Result<Option<BatchReceipt>, ApplyError> {
    let guard = Guard::open_with(root, None, hook)?;
    if !guard.io(guard.directory.exists("active"))? {
        return Ok(None);
    }
    let active = guard.io(guard.directory.child("active"))?;
    root_layout(&guard, &active)?;
    if !guard.io(active.exists("batch-plan.json"))? {
        // Before publication, no entry or destination change is permitted.
        // Never infer this safe stopping state from a different layout.
        for name in guard.io(active.entry_names(129))? {
            if name == "manifest.json" {
                continue;
            }
            if (!pending_record(&name, "batch-plan.json")
                && !pending_record(&name, "manifest.json"))
                || guard.io(active.regular_entry(&name))? != Some(true)
            {
                return Err(guard.invalid("missing preparation with other transaction evidence"));
            }
            guard.io(active.read_record_with_limit(&name, MAX_INTENT_BYTES))?;
        }
        let retained = archive_directory(&guard, &active, hook)?;
        return Ok(Some(BatchReceipt {
            outcome: BatchOutcome::Unprepared,
            outputs: Vec::new(),
            retained,
        }));
    }
    let preparation: Preparation = decode(&guard, &active, "batch-plan.json")?;
    validate_preparation(&guard, &active, &preparation)?;
    if !guard.io(active.exists("batch.json"))? {
        return incomplete_preparation(&guard, &active, &preparation, hook).map(Some);
    }
    let complete: CompleteIntent = decode(&guard, &active, "batch.json")?;
    resume(&guard, &active, &preparation, &complete, hook).map(Some)
}

fn resume(
    guard: &Guard,
    active: &Directory,
    preparation: &Preparation,
    complete: &CompleteIntent,
    hook: &mut impl FnMut(Point) -> io::Result<()>,
) -> Result<BatchReceipt, ApplyError> {
    root_layout(guard, active)?;
    validate_preparation(guard, active, preparation)?;
    if complete.schema != BATCH_SCHEMA
        || complete.transaction != preparation.transaction
        || complete.preparation != preparation.identity
        || complete.entries.len() != preparation.plans.len()
        || complete.identity != complete_identity(complete)?
    {
        return Err(guard.invalid("complete batch identity mismatch"));
    }
    let directories = guard.io(active.child("entries"))?;
    validate_indices(guard, &directories, complete.entries.len(), true)?;
    let mut paths = Vec::with_capacity(complete.entries.len());
    for (index, journal) in complete.entries.iter().enumerate() {
        if journal.plan != preparation.plans[index] {
            return Err(guard.invalid("entry differs from batch preparation"));
        }
        let path = output_path(guard, &journal.plan.path)?;
        let entry = at_path(&path, guard.io(directories.child(&entry_name(index))))?;
        at_path(&path, validate_journal(guard, &entry, journal))?;
        entry_layout(guard, &entry)?;
        paths.push(path);
    }
    let stopped = if guard.io(active.exists("stop.json"))? {
        let record: StopRecord = decode(guard, active, "stop.json")?;
        if record.identity != complete.identity {
            return Err(guard.invalid("stop record belongs to another batch"));
        }
        true
    } else {
        false
    };
    let states = observations(guard, &directories, complete, &paths)?;
    if stopped
        || states
            .iter()
            .any(|state| state.restoring || matches!(state.state, State::Conflict(_)))
    {
        return settle_conflict(guard, active, &directories, complete, &paths, hook);
    }
    for (index, journal) in complete.entries.iter().enumerate() {
        let entry = at_path(
            &paths[index],
            guard.io(directories.child(&entry_name(index))),
        )?;
        let state = at_path(&paths[index], inspect(guard, &entry, complete, journal))?;
        if state.restoring || matches!(state.state, State::Conflict(_)) {
            return settle_conflict(guard, active, &directories, complete, &paths, hook);
        }
        if matches!(state.state, State::Applied) {
            at_path(
                &paths[index],
                reconcile_sync(guard, &entry, journal, state, index, hook),
            )?;
            continue;
        }
        let result = (|| {
            let (parent, name) = guard.parent(&journal.plan)?;
            if matches!(state.state, State::Baseline) {
                emit(guard, hook, Some(index), Phase::BaselineChecked)?;
                guard.parent(&journal.plan)?;
                if journal.plan.expected.is_some() {
                    guard.io(parent.rename_to(name, &entry, "before"))?;
                    guard.io(parent.sync())?;
                    guard.io(entry.sync())?;
                    emit(guard, hook, Some(index), Phase::Moved)?;
                    if entry.fingerprint("before").ok().flatten() != journal.plan.expected {
                        return Ok(false);
                    }
                }
            }
            emit(guard, hook, Some(index), Phase::BeforeInstall)?;
            guard.parent(&journal.plan)?;
            if guard.io(entry.fingerprint("after"))? != Some(journal.staged.clone()) {
                return Err(guard.invalid("staged entry changed before installation"));
            }
            guard.io(entry.rename_to("after", &parent, name))?;
            emit(guard, hook, Some(index), Phase::InstallSync)?;
            guard.io(parent.sync())?;
            guard.io(entry.sync())?;
            emit(guard, hook, Some(index), Phase::Installed)?;
            let done = DoneRecord {
                identity: complete.identity,
                plan_identity: journal.plan_identity,
            };
            guard.io(entry.record("done.json", &encode(&done)?, &mut |point| {
                hook(Point::Batch {
                    file: Some(index),
                    phase: Phase::DoneRecord(point),
                })
            }))?;
            Ok(true)
        })();
        if !at_path(&paths[index], result)? {
            return settle_conflict(guard, active, &directories, complete, &paths, hook);
        }
    }
    let final_states = observations(guard, &directories, complete, &paths)?;
    if final_states
        .iter()
        .all(|state| matches!(state.state, State::Applied) && !state.restoring)
    {
        let outputs = reports(paths, final_states);
        let retained = archive_directory(guard, active, hook)?;
        Ok(BatchReceipt {
            outcome: BatchOutcome::Applied,
            outputs,
            retained,
        })
    } else {
        settle_conflict(guard, active, &directories, complete, &paths, hook)
    }
}

#[derive(Debug, Clone, Copy)]
enum State {
    Baseline,
    Moved,
    Applied,
    Conflict(ConflictReason),
}

#[derive(Debug, Clone, Copy)]
struct Observation {
    state: State,
    restoring: bool,
}

fn inspect(
    guard: &Guard,
    entry: &Directory,
    complete: &CompleteIntent,
    journal: &Journal,
) -> Result<Observation, ApplyError> {
    entry_layout(guard, entry)?;
    let (parent, name) = guard.parent(&journal.plan)?;
    if guard.io(entry.exists("done.json"))? {
        let done: DoneRecord = decode(guard, entry, "done.json")?;
        if done.identity != complete.identity || done.plan_identity != journal.plan_identity {
            return Err(guard.invalid("entry completion record identity mismatch"));
        }
    }
    let before_exists = guard.io(entry.exists("before"))?;
    if guard.io(entry.exists("restore.json"))? {
        let restored: RestoreRecord = decode(guard, entry, "restore.json")?;
        if restored.plan_identity != journal.plan_identity {
            return Err(guard.invalid("restore intent identity mismatch"));
        }
        if before_exists {
            if guard.io(entry.entry_identity("before"))? != restored.entry {
                return Err(guard.invalid("restore source identity changed"));
            }
            return Ok(Observation {
                state: if guard.io(parent.exists(name))? {
                    State::Conflict(ConflictReason::DestinationChanged)
                } else {
                    State::Moved
                },
                restoring: true,
            });
        }
        let same_entry = guard.io(parent.exists(name))?
            && guard.io(parent.entry_identity(name))? == restored.entry;
        let baseline = same_entry
            && !restored.changed
            && guard.io(parent.fingerprint(name))? == journal.plan.expected;
        return Ok(Observation {
            state: if baseline {
                State::Baseline
            } else {
                State::Conflict(ConflictReason::RestorationObserved)
            },
            restoring: true,
        });
    }
    if guard.io(parent.regular_entry(name))? == Some(false) {
        return Ok(Observation {
            state: State::Conflict(ConflictReason::NonRegularDestination),
            restoring: false,
        });
    }
    let target = guard.io(parent.fingerprint(name))?;
    if target.as_ref() == Some(&journal.staged) {
        let backup_ok = match &journal.plan.expected {
            Some(expected) => {
                before_exists && guard.io(entry.entry_identity("before"))? == expected.identity
            }
            None => !before_exists,
        };
        return Ok(Observation {
            state: if backup_ok {
                State::Applied
            } else {
                State::Conflict(ConflictReason::MissingBackup)
            },
            restoring: false,
        });
    }
    if target.is_some() && target != journal.plan.expected {
        return Ok(Observation {
            state: State::Conflict(ConflictReason::DestinationChanged),
            restoring: false,
        });
    }
    if before_exists {
        if target.is_some() || journal.plan.expected.is_none() {
            return Ok(Observation {
                state: State::Conflict(ConflictReason::DestinationChanged),
                restoring: false,
            });
        }
        // Consumed staging indicates installation. Preserve a later deletion
        // rather than putting the old baseline back in its place.
        if !guard.io(entry.exists("after"))? || guard.io(entry.exists("done.json"))? {
            return Ok(Observation {
                state: State::Conflict(ConflictReason::MissingDestination),
                restoring: false,
            });
        }
        if entry.fingerprint("before").ok().flatten() != journal.plan.expected {
            return Ok(Observation {
                state: State::Conflict(ConflictReason::MovedEntryChanged),
                restoring: false,
            });
        }
        if guard.io(entry.fingerprint("after"))? != Some(journal.staged.clone()) {
            return Ok(Observation {
                state: State::Conflict(ConflictReason::MissingStage),
                restoring: false,
            });
        }
        return Ok(Observation {
            state: State::Moved,
            restoring: false,
        });
    }
    if target == journal.plan.expected
        && guard.io(entry.fingerprint("after"))? == Some(journal.staged.clone())
    {
        return Ok(Observation {
            state: State::Baseline,
            restoring: false,
        });
    }
    Ok(Observation {
        state: State::Conflict(if target.is_none() {
            ConflictReason::MissingDestination
        } else {
            ConflictReason::MissingStage
        }),
        restoring: false,
    })
}

fn settle_conflict(
    guard: &Guard,
    active: &Directory,
    directories: &Directory,
    complete: &CompleteIntent,
    paths: &[OutputPath],
    hook: &mut impl FnMut(Point) -> io::Result<()>,
) -> Result<BatchReceipt, ApplyError> {
    if !guard.io(active.exists("stop.json"))? {
        let stop = StopRecord {
            identity: complete.identity,
            reason: ConflictReason::RestorationObserved,
        };
        guard.io(active.record("stop.json", &encode(&stop)?, &mut |point| {
            hook(Point::Batch {
                file: None,
                phase: Phase::StopRecord(point),
            })
        }))?;
    }
    for (index, journal) in complete.entries.iter().enumerate() {
        let entry = at_path(
            &paths[index],
            guard.io(directories.child(&entry_name(index))),
        )?;
        let (parent, name) = at_path(&paths[index], guard.parent(&journal.plan))?;
        let restoring = guard.io(entry.exists("restore.json"))?;
        let unfinished_move = !guard.io(entry.exists("done.json"))?
            && guard.io(entry.fingerprint("after"))? == Some(journal.staged.clone());
        if !guard.io(parent.exists(name))?
            && guard.io(entry.exists("before"))?
            && (restoring || unfinished_move)
        {
            let changed = entry.fingerprint("before").ok().flatten() != journal.plan.expected;
            let _outcome = at_path(
                &paths[index],
                restore_entry(guard, &entry, journal, changed, &mut file_hook(index, hook)),
            )?;
        }
        let state = at_path(&paths[index], inspect(guard, &entry, complete, journal))?;
        at_path(
            &paths[index],
            reconcile_sync(guard, &entry, journal, state, index, hook),
        )?;
    }
    let states = observations(guard, directories, complete, paths)?;
    let outputs = reports(paths.to_vec(), states);
    let retained = archive_directory(guard, active, hook)?;
    Ok(BatchReceipt {
        outcome: BatchOutcome::Conflict,
        outputs,
        retained,
    })
}

fn reconcile_sync(
    guard: &Guard,
    entry: &Directory,
    journal: &Journal,
    state: Observation,
    index: usize,
    hook: &mut impl FnMut(Point) -> io::Result<()>,
) -> Result<(), ApplyError> {
    let installed = matches!(state.state, State::Applied);
    let restored = state.restoring && !guard.io(entry.exists("before"))?;
    if installed || restored {
        let (parent, name) = guard.parent(&journal.plan)?;
        if installed {
            guard.io(guard.io(parent.open(name))?.sync_all())?;
        }
        emit(guard, hook, Some(index), Phase::ReconcileSync)?;
        guard.io(parent.sync())?;
        guard.io(entry.sync())?;
    }
    Ok(())
}

fn incomplete_preparation(
    guard: &Guard,
    active: &Directory,
    preparation: &Preparation,
    hook: &mut impl FnMut(Point) -> io::Result<()>,
) -> Result<BatchReceipt, ApplyError> {
    let directories = if guard.io(active.exists("entries"))? {
        Some(guard.io(active.child("entries"))?)
    } else {
        None
    };
    if let Some(directory) = &directories {
        validate_indices(guard, directory, preparation.plans.len(), false)?;
        for name in guard.io(directory.entry_names(MAX_FILES))? {
            let entry = guard.io(directory.child(&name))?;
            entry_layout(guard, &entry)?;
            if guard.io(entry.exists("before"))?
                || guard.io(entry.exists("restore.json"))?
                || guard.io(entry.exists("done.json"))?
            {
                return Err(
                    guard.invalid("missing complete intent with evidence of destination changes")
                );
            }
        }
    }
    let mut outputs = Vec::with_capacity(preparation.plans.len());
    for plan in &preparation.plans {
        let path = output_path(guard, &plan.path)?;
        let (parent, name) = at_path(&path, guard.parent(plan))?;
        if at_path(&path, guard.io(parent.fingerprint(name)))? != plan.expected {
            return Err(guard
                .conflict("incomplete staging has a changed destination; retaining all records"));
        }
        outputs.push(OutputReport {
            path,
            disposition: OutputDisposition::Baseline,
        });
    }
    let retained = archive_directory(guard, active, hook)?;
    Ok(BatchReceipt {
        outcome: BatchOutcome::BaselineVerified,
        outputs,
        retained,
    })
}

fn observations(
    guard: &Guard,
    directories: &Directory,
    complete: &CompleteIntent,
    paths: &[OutputPath],
) -> Result<Vec<Observation>, ApplyError> {
    complete
        .entries
        .iter()
        .enumerate()
        .map(|(index, journal)| {
            let directory = at_path(
                &paths[index],
                guard.io(directories.child(&entry_name(index))),
            )?;
            at_path(&paths[index], inspect(guard, &directory, complete, journal))
        })
        .collect()
}

fn reports(paths: Vec<OutputPath>, observations: Vec<Observation>) -> Vec<OutputReport> {
    paths
        .into_iter()
        .zip(observations)
        .map(|(path, observation)| OutputReport {
            path,
            disposition: match observation.state {
                State::Applied => OutputDisposition::Applied,
                State::Baseline => OutputDisposition::Baseline,
                State::Moved => OutputDisposition::Conflict(ConflictReason::MissingDestination),
                State::Conflict(reason) => OutputDisposition::Conflict(reason),
            },
        })
        .collect()
}

fn validate_preparation(
    guard: &Guard,
    active: &Directory,
    preparation: &Preparation,
) -> Result<(), ApplyError> {
    if preparation.schema != BATCH_SCHEMA
        || preparation.plans.is_empty()
        || preparation.plans.len() > MAX_FILES
        || preparation.transaction != guard.io(active.identity())?
        || preparation.identity != preparation_identity(preparation)?
    {
        return Err(guard.invalid("batch preparation identity or count mismatch"));
    }
    let canonical = OutputBundle::new(
        preparation
            .plans
            .iter()
            .map(|plan| (plan.path.clone(), String::new())),
    )
    .map_err(|_| guard.invalid("invalid or ambiguous batch output paths"))?;
    if !canonical
        .iter()
        .map(|(path, _)| path.as_str())
        .eq(preparation.plans.iter().map(|plan| plan.path.as_str()))
    {
        return Err(guard.invalid("batch paths are not in canonical order"));
    }
    let mut output_bytes = 0_u64;
    let mut baseline_bytes = 0_u64;
    for plan in &preparation.plans {
        super::validate_path(&plan.path).map_err(|_| guard.invalid("invalid batch path"))?;
        guard.ensure_root(plan)?;
        if plan.schema != super::SCHEMA
            || plan.parents.len() != plan.path.split('/').count() - 1
            || plan.intended_length > super::fs::MAX_FILE_BYTES
            || plan.attributes.mode & !0o777 != 0
            || plan
                .expected
                .as_ref()
                .map_or(plan.attributes.mode != 0o600, |expected| {
                    expected.length > super::fs::MAX_FILE_BYTES
                        || expected.mode & !0o777 != 0
                        || super::Attributes::of(expected) != plan.attributes
                })
        {
            return Err(guard.invalid("invalid captured batch file manifest"));
        }
        output_bytes = output_bytes
            .checked_add(plan.intended_length)
            .ok_or_else(|| guard.invalid("batch byte count overflow"))?;
        baseline_bytes = baseline_bytes
            .checked_add(plan.expected.as_ref().map_or(0, |value| value.length))
            .ok_or_else(|| guard.invalid("batch baseline count overflow"))?;
    }
    if output_bytes > MAX_OUTPUT_BYTES || baseline_bytes > MAX_BASELINE_BYTES {
        return Err(guard.invalid("batch exceeds aggregate byte limits"));
    }
    Ok(())
}

fn root_layout(guard: &Guard, active: &Directory) -> Result<(), ApplyError> {
    let names = guard.io(active.entry_names(512))?;
    for name in &names {
        if !matches!(
            name.as_str(),
            "manifest.json" | "batch-plan.json" | "batch.json" | "stop.json" | "entries"
        ) && ![
            "manifest.json",
            "batch-plan.json",
            "batch.json",
            "stop.json",
        ]
        .iter()
        .any(|record| pending_record(name, record))
        {
            return Err(guard.invalid("unknown or mixed transaction layout"));
        }
    }
    if guard.io(active.exists("manifest.json"))? {
        if guard.io(active.read_record("manifest.json"))? != COMPATIBILITY_MARKER {
            return Err(guard.invalid("foreign or unsupported batch compatibility marker"));
        }
    } else if names
        .iter()
        .any(|name| !pending_record(name, "manifest.json"))
    {
        return Err(guard.invalid("batch evidence exists without its compatibility marker"));
    }
    Ok(())
}

fn entry_layout(guard: &Guard, entry: &Directory) -> Result<(), ApplyError> {
    for name in guard.io(entry.entry_names(256))? {
        if !matches!(
            name.as_str(),
            "after" | "before" | "restore.json" | "done.json"
        ) && !pending_record(&name, "restore.json")
            && !pending_record(&name, "done.json")
        {
            return Err(guard.invalid("unknown batch entry layout"));
        }
    }
    Ok(())
}

fn validate_indices(
    guard: &Guard,
    directory: &Directory,
    count: usize,
    complete: bool,
) -> Result<(), ApplyError> {
    let names = guard.io(directory.entry_names(MAX_FILES))?;
    if complete && names.len() != count {
        return Err(guard.invalid("batch entry count mismatch"));
    }
    if names
        .iter()
        .any(|name| !(0..count).any(|index| entry_name(index) == *name))
    {
        return Err(guard.invalid("unexpected batch entry index"));
    }
    Ok(())
}

fn entry_name(index: usize) -> String {
    format!("{index:04}")
}

fn preparation_identity(preparation: &Preparation) -> Result<[u8; 32], ApplyError> {
    encode(&(
        preparation.schema,
        preparation.transaction,
        &preparation.plans,
    ))
    .map(|bytes| super::fs::digest(&bytes))
}

fn complete_identity(complete: &CompleteIntent) -> Result<[u8; 32], ApplyError> {
    encode(&(
        complete.schema,
        complete.transaction,
        complete.preparation,
        &complete.entries,
    ))
    .map(|bytes| super::fs::digest(&bytes))
}

fn encode(value: &impl Serialize) -> Result<Vec<u8>, ApplyError> {
    let bytes = serde_json::to_vec(value)
        .map_err(|_| ApplyError::Invalid("batch record encoding failed"))?;
    if bytes.len() as u64 > MAX_INTENT_BYTES {
        return Err(ApplyError::Invalid("batch record exceeds 2 MiB"));
    }
    Ok(bytes)
}

fn decode<T: serde::de::DeserializeOwned>(
    guard: &Guard,
    directory: &Directory,
    name: &str,
) -> Result<T, ApplyError> {
    serde_json::from_slice(&guard.io(directory.read_record_with_limit(name, MAX_INTENT_BYTES))?)
        .map_err(|_| guard.invalid("malformed or unsupported batch record"))
}

fn output_path(guard: &Guard, path: &str) -> Result<OutputPath, ApplyError> {
    OutputPath::new(path.to_owned()).map_err(|_| guard.invalid("invalid batch output path"))
}

fn at_path<T>(path: &OutputPath, result: Result<T, ApplyError>) -> Result<T, ApplyError> {
    result.map_err(|source| ApplyError::Output {
        path: path.clone(),
        source: Box::new(source),
    })
}

fn emit(
    guard: &Guard,
    hook: &mut impl FnMut(Point) -> io::Result<()>,
    file: Option<usize>,
    phase: Phase,
) -> Result<(), ApplyError> {
    guard.io(hook(Point::Batch { file, phase }))
}

fn file_hook(
    index: usize,
    hook: &mut impl FnMut(Point) -> io::Result<()>,
) -> impl FnMut(Point) -> io::Result<()> + '_ {
    move |point| {
        let phase = match point {
            Point::StageSync => Phase::StageSync,
            Point::Record(RecordKind::Restore, point) => Phase::RestoreRecord(point),
            Point::BeforeRestore => Phase::BeforeRestore,
            Point::RestoreSync => Phase::RestoreSync,
            _ => return hook(point),
        };
        hook(Point::Batch {
            file: Some(index),
            phase,
        })
    }
}

