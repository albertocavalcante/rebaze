//! Third-party dependency configuration and generation.
//!
//! This module generates extensible BUILD files for third-party dependencies,
//! supporting multiple resolution strategies:
//!
//! - `system`: Use system-installed libraries via new_local_repository (non-hermetic)
//! - `source`: Build from source using rules_foreign_cc (hermetic)
//! - `conan`: Use Conan package manager
//! - `vcpkg`: Use vcpkg package manager
//! - `prebuilt`: Use pre-built libraries from filesystem
//! - `bazelle`: Use bazelle/gazelle_cc to generate BUILD files
//! - `custom`: User-defined resolution

use crate::starlark::{Alias, CcLibrary, Cmake, ConfigureMake, FunctionCall, Meson};
use rebaze_cmake::PkgConfigModule;
use std::collections::{BTreeMap, BTreeSet};

/// Deduplicate pkg-config modules by their normalized target name.
///
/// Returns a new `Vec` with duplicates removed, preserving the order of first occurrence.
/// Uses BTreeSet for deterministic deduplication behavior.
pub fn deduplicate_modules(modules: &[PkgConfigModule]) -> Vec<PkgConfigModule> {
    let mut seen = BTreeSet::new();
    modules
        .iter()
        .filter(|pkg| {
            let target_name = pkg.prefix.to_lowercase().replace('-', "_");
            seen.insert(target_name)
        })
        .cloned()
        .collect()
}

/// Dependency resolution strategy.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum DepsStrategy {
    /// Use system libraries via new_local_repository (non-hermetic, but works)
    /// This is the default since it works out of the box when deps are installed.
    #[default]
    System,
    /// Build from source using rules_foreign_cc (hermetic, recommended for production)
    Source,
    /// Use Conan package manager
    Conan,
    /// Use vcpkg package manager
    Vcpkg,
    /// Use pre-built libraries from filesystem
    Prebuilt,
    /// Use bazelle/gazelle_cc to generate BUILD files for deps
    Bazelle,
    /// User provides custom resolution
    Custom,
}

/// Configuration for third-party dependency generation.
#[derive(Debug, Clone, Default)]
pub struct ThirdPartyConfig {
    /// Default strategy for resolving dependencies
    pub default_strategy: DepsStrategy,
    /// Path to prebuilt libraries (for Prebuilt strategy)
    pub prebuilt_path: Option<String>,
    /// Conan profile to use
    pub conan_profile: Option<String>,
    /// vcpkg triplet to use
    pub vcpkg_triplet: Option<String>,
}

/// Generate the third_party/BUILD.bazel file.
#[allow(clippy::option_if_let_else)]
pub fn generate_build_file(
    pkg_config_modules: &[PkgConfigModule],
    _config: &ThirdPartyConfig,
) -> String {
    // Check if any pkg-config packages are available on this system
    let any_pkg_config_available = pkg_config_modules
        .iter()
        .any(|pkg| probe_pkg_config(&pkg.packages).is_some());

    let pkg_config_note = if any_pkg_config_available {
        "# NOTE: System library flags were detected via pkg-config during migration.\n#       These paths are system-specific and may need adjustment on other machines."
    } else {
        "# NOTE: pkg-config was not available during migration.\n#       You need to add copts for include paths. Run: pkg-config --cflags <package>"
    };

    let mut lines = vec![
        format!(
            r#"# Third-party dependencies - Generated by rebaze
#
# This file provides extensible dependency resolution. Edit third_party/config.bzl
# to configure how dependencies are resolved.
#
# Supported strategies:
#   - system:   Use system libraries via pkg-config (non-hermetic)
#   - source:   Build from source with rules_foreign_cc (hermetic, recommended)
#   - conan:    Use Conan package manager
#   - vcpkg:    Use vcpkg package manager
#   - prebuilt: Use pre-compiled libraries from filesystem
#   - custom:   Implement your own resolution in config.bzl
#
{pkg_config_note}

load("@rules_cc//cc:defs.bzl", "cc_library")
load("//third_party:config.bzl", "DEPS_CONFIG", "resolve_dep")

package(default_visibility = ["//visibility:public"])"#
        ),
        String::new(),
    ];

    // Generate an alias for each dependency that uses the configured resolver
    for pkg in pkg_config_modules {
        let target_name = pkg.prefix.to_lowercase().replace('-', "_");
        let packages_str = pkg.packages.join(", ");

        let alias = Alias {
            name: target_name.clone(),
            actual: FunctionCall {
                name: "resolve_dep",
                args: vec![target_name],
            },
        };

        lines.push(format!("# {} -> {}", pkg.prefix, packages_str));
        if let Ok(alias_str) = crate::starlark::serde_starlark::to_string(&alias) {
            lines.push(alias_str);
        }
        lines.push(String::new());
    }

    // Generate fallback cc_library rules for system strategy
    lines.push("# ============================================================".to_string());
    lines.push("# System library fallbacks (used when strategy = \"system\")".to_string());
    lines.push("# ============================================================".to_string());
    lines.push(String::new());

    for pkg in pkg_config_modules {
        let target_name = pkg.prefix.to_lowercase().replace('-', "_");
        let packages_str = pkg.packages.join(", ");

        // Try to detect actual flags from pkg-config
        let detected_flags = probe_pkg_config(&pkg.packages);

        // NOTE: We only include linkopts here, NOT copts with include paths.
        // Include paths must go in .bazelrc as --copt=-isystem/path because
        // rules_cc validates include paths in copts and rejects absolute system paths.

        let (linkopts, needs_todo) = if let Some(ref flags) = detected_flags {
            // Extract only linker flags (not -I or other compiler flags)
            let opts: Vec<String> = flags
                .libs
                .iter()
                .filter(|f| f.starts_with("-l") || f.starts_with("-L"))
                .cloned()
                .collect();
            (opts, false)
        } else {
            // Fallback to guessed linkopts when pkg-config not available
            (generate_system_linkopts(&pkg.packages), true)
        };

        let cc_lib = CcLibrary {
            name: format!("{target_name}_system"),
            linkopts,
            ..Default::default()
        };

        if let Ok(lib_str) = crate::starlark::serde_starlark::to_string(&cc_lib) {
            lines.push(lib_str);
        }

        if needs_todo {
            lines.push("# TODO: pkg-config not available. Add linkopts from:".to_string());
            lines.push(format!("# pkg-config --libs {packages_str}"));
        }

        lines.push(String::new());
    }

    lines.join("\n")
}

/// Generate the third_party/config.bzl file.
pub fn generate_config_bzl(
    pkg_config_modules: &[PkgConfigModule],
    config: &ThirdPartyConfig,
) -> String {
    let default_strategy = match config.default_strategy {
        DepsStrategy::System => "system",
        DepsStrategy::Source => "source",
        DepsStrategy::Conan => "conan",
        DepsStrategy::Vcpkg => "vcpkg",
        DepsStrategy::Prebuilt => "prebuilt",
        DepsStrategy::Bazelle => "bazelle",
        DepsStrategy::Custom => "custom",
    };

    let mut lines = vec![
        format!(
            r#""""Configuration for third-party dependencies.

Edit this file to customize how dependencies are resolved.
"""

# Default resolution strategy for all dependencies.
# Options: "system", "source", "conan", "vcpkg", "prebuilt", "custom"
DEFAULT_STRATEGY = "{default_strategy}"

# Per-dependency configuration.
# Override the strategy or provide additional config for specific deps.
DEPS_CONFIG = {{"#
        ),
    ];

    // Generate config entries for each dependency
    for pkg in pkg_config_modules {
        let target_name = pkg.prefix.to_lowercase().replace('-', "_");
        let packages: Vec<_> = pkg
            .packages
            .iter()
            .map(|p| format!("\"{p}\""))
            .collect();

        lines.push(format!(
            r#"    "{target_name}": {{
        "pkg_config": [{packages}],
        # "strategy": "system",  # Override default strategy
        # "conan_package": "glib/2.76.0",
        # "vcpkg_package": "glib",
        # "prebuilt_path": "/opt/libs/{target_name}",
        # "source_url": "https://...",
    }},"#,
            packages = packages.join(", ")
        ));
    }

    lines.push("}".to_string());
    lines.push(String::new());

    // Add the resolver function
    lines.push(
        r#"def resolve_dep(name):
    """Resolve a dependency based on configuration.

    Args:
        name: The dependency name (e.g., "glib")

    Returns:
        A label pointing to the resolved dependency target.
    """
    config = DEPS_CONFIG.get(name, {})
    strategy = config.get("strategy", DEFAULT_STRATEGY)

    if strategy == "system":
        # Use new_local_repository wrapper from system_deps module extension
        return "@system_{}//:{}".format(name, name)
    elif strategy == "source":
        return "//third_party:{}_source".format(name)
    elif strategy == "conan":
        return "@conan_{}//:{}".format(name, name)
    elif strategy == "vcpkg":
        return "@vcpkg_{}//:{}".format(name, name)
    elif strategy == "prebuilt":
        return "//third_party:{}_prebuilt".format(name)
    elif strategy == "bazelle":
        # Use bazelle/gazelle_cc generated BUILD files
        return "@{}_src//:{}".format(name, name)
    elif strategy == "custom":
        # Users implement custom_resolve_dep in config_custom.bzl
        return custom_resolve_dep(name, config)
    else:
        fail("Unknown dependency strategy: " + strategy)

def custom_resolve_dep(name, config):
    """Override this function in config_custom.bzl for custom resolution.

    Example config_custom.bzl:
        def custom_resolve_dep(name, config):
            return "@my_internal_repo//libs:" + name
    """
    fail("Custom resolution not implemented. Create config_custom.bzl and implement custom_resolve_dep()")"#
            .to_string(),
    );

    lines.join("\n")
}

