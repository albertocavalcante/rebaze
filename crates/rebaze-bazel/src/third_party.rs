/// Generate the third_party/source.bzl file for building from source.
#[allow(clippy::too_many_lines)]
pub fn generate_source_bzl(pkg_config_modules: &[PkgConfigModule]) -> String {
    let mut lines = vec![
        r#""""Build third-party dependencies from source using rules_foreign_cc.

This provides hermetic, reproducible builds but requires more setup.

Usage:
  1. In MODULE.bazel, use the source_deps extension:
     source_deps = use_extension("//third_party:source.bzl", "source_deps")
     use_repo(source_deps, "glib_src", "pcre2_src", ...)

  2. In third_party/config.bzl, set strategy to "source":
     DEFAULT_STRATEGY = "source"

  3. Build targets will be available as //third_party:<name>_source
"""

load("@rules_foreign_cc//foreign_cc:defs.bzl", "cmake", "configure_make", "meson")

# Source configurations for each dependency.
# These are populated with known good defaults where available.
SOURCES = {"#
            .to_string(),
    ];

    // Collect all unique packages including transitive deps
    let mut all_packages = std::collections::BTreeSet::new();
    for pkg in pkg_config_modules {
        let name = pkg.prefix.to_lowercase().replace('-', "_");
        all_packages.insert(name.clone());

        // Add known transitive deps
        if let Some(info) = get_known_package_info(&name) {
            for dep in info.deps {
                all_packages.insert(dep.to_string());
            }
        }
    }

    for pkg_name in &all_packages {
        if let Some(info) = get_known_package_info(pkg_name) {
            let deps_str = if info.deps.is_empty() {
                String::new()
            } else {
                format!(
                    "\n        \"deps\": [{}],",
                    info.deps.iter().map(|d| format!("\"{d}\"")).collect::<Vec<_>>().join(", ")
                )
            };

            let meson_opts_str = if info.meson_options.is_empty() {
                String::new()
            } else {
                format!(
                    "\n        \"meson_options\": [{}],",
                    info.meson_options.iter().map(|o| format!("\"{o}\"")).collect::<Vec<_>>().join(", ")
                )
            };

            let out_libs_str = info.out_libs.iter()
                .map(|l| format!("\"{l}\""))
                .collect::<Vec<_>>()
                .join(", ");

            lines.push(format!(
                r#"    "{name}": {{
        "url": "{url}",
        "sha256": "{sha256}",
        "strip_prefix": "{strip_prefix}",
        "build_system": "{build_system}",
        "out_static_libs": [{out_libs}],{deps}{meson_opts}
    }},"#,
                name = info.name,
                url = info.url,
                sha256 = info.sha256,
                strip_prefix = info.strip_prefix,
                build_system = info.build_system,
                out_libs = out_libs_str,
                deps = deps_str,
                meson_opts = meson_opts_str,
            ));
        } else {
            // Unknown package - generate placeholder
            lines.push(format!(
                r#"    "{pkg_name}": {{
        # TODO: Configure source build for {pkg_name}
        # "url": "https://...",
        # "sha256": "...",
        # "strip_prefix": "...",
        # "build_system": "cmake",  # or "autotools", "meson"
        # "out_static_libs": ["lib{pkg_name}.a"],
    }},"#
            ));
        }
    }

    lines.push("}".to_string());
    lines.push(String::new());

    // Add the module extension for downloading sources
    lines.push(r#"def _source_repo_impl(repository_ctx):
    """Download and prepare source repository."""
    repository_ctx.download_and_extract(
        url = repository_ctx.attr.url,
        sha256 = repository_ctx.attr.sha256,
        stripPrefix = repository_ctx.attr.strip_prefix,
    )

    # Create BUILD.bazel that exports all sources
    repository_ctx.file("BUILD.bazel", '''
filegroup(
    name = "all",
    srcs = glob(["**"]),
    visibility = ["//visibility:public"],
)
''')

_source_repo = repository_rule(
    implementation = _source_repo_impl,
    attrs = {
        "url": attr.string(mandatory = True),
        "sha256": attr.string(default = ""),
        "strip_prefix": attr.string(default = ""),
    },
)

def _source_deps_impl(module_ctx):
    """Download all configured source dependencies."""
    for name, config in SOURCES.items():
        if "url" not in config:
            continue
        _source_repo(
            name = name + "_src",
            url = config["url"],
            sha256 = config.get("sha256", ""),
            strip_prefix = config.get("strip_prefix", ""),
        )

source_deps = module_extension(
    implementation = _source_deps_impl,
)"#.to_string());

    lines.join("\n")
}

/// Generate BUILD targets for source dependencies.
pub fn generate_source_build_targets(pkg_config_modules: &[PkgConfigModule]) -> String {
    let mut lines = vec![
        r#"# Source build targets using rules_foreign_cc
# These build dependencies from source for hermetic builds.

load("@rules_foreign_cc//foreign_cc:defs.bzl", "cmake", "configure_make", "meson")
load("//third_party:source.bzl", "SOURCES")
"#.to_string(),
    ];

    // Collect all packages including transitive deps
    let mut all_packages = std::collections::BTreeSet::new();
    for pkg in pkg_config_modules {
        let name = pkg.prefix.to_lowercase().replace('-', "_");
        all_packages.insert(name.clone());
        if let Some(info) = get_known_package_info(&name) {
            for dep in info.deps {
                all_packages.insert(dep.to_string());
            }
        }
    }

    for pkg_name in &all_packages {
        if let Some(info) = get_known_package_info(pkg_name) {
            let name = format!("{}_source", info.name);
            let lib_source = format!("@{}_src//:all", info.name);
            let deps: Vec<String> = info
                .deps
                .iter()
                .map(|d| format!(":{d}_source"))
                .collect();

            let rule_str = match info.build_system {
                "meson" => {
                    let options: BTreeMap<String, String> = info
                        .meson_options
                        .iter()
                        .map(|o| {
                            let parts: Vec<&str> =
                                o.trim_start_matches('-').splitn(2, '=').collect();
                            if parts.len() == 2 {
                                (parts[0].to_string(), parts[1].to_string())
                            } else {
                                (parts[0].to_string(), "true".to_string())
                            }
                        })
                        .collect();

                    let rule = Meson::new(name, lib_source)
                        .with_static_libs(info.out_libs.clone())
                        .with_options(options)
                        .with_deps(deps)
                        .with_visibility_public();
                    crate::starlark::serde_starlark::to_string(&rule).ok()
                }
                "cmake" => {
                    let rule = Cmake::new(name, lib_source)
                        .with_static_libs(info.out_libs.clone())
                        .with_deps(deps)
                        .with_visibility_public();
                    crate::starlark::serde_starlark::to_string(&rule).ok()
                }
                "autotools" => {
                    let rule = ConfigureMake::new(name, lib_source)
                        .with_static_libs(info.out_libs.clone())
                        .with_deps(deps)
                        .with_visibility_public();
                    crate::starlark::serde_starlark::to_string(&rule).ok()
                }
                _ => None,
            };

            if let Some(rule) = rule_str {
                lines.push(format!("\n{rule}"));
            }
        } else {
            // Unknown package - generate placeholder
            lines.push(format!(
                r#"
# TODO: Configure source build for {pkg_name}
# Uncomment and adjust after configuring SOURCES["{pkg_name}"] in source.bzl
#
# cmake(
#     name = "{pkg_name}_source",
#     lib_source = "@{pkg_name}_src//:all",
#     out_static_libs = ["lib{pkg_name}.a"],
#     visibility = ["//visibility:public"],
# )
"#
            ));
        }
    }

    lines.join("\n")
}

/// Detected system library info from pkg-config.
#[derive(Debug, Clone)]
pub struct SystemLibInfo {
    /// Library name (e.g., "glib")
    pub name: String,
    /// pkg-config package names
    pub packages: Vec<String>,
    /// Detected install prefix (e.g., /opt/homebrew/Cellar/glib/2.86.3)
    pub prefix: Option<String>,
    /// Include directories relative to prefix
    pub include_dirs: Vec<String>,
    /// Library directories relative to prefix
    pub lib_dirs: Vec<String>,
    /// Library names to link
    pub libs: Vec<String>,
}

/// Probe pkg-config to get detailed library info.
pub fn probe_system_lib(packages: &[String]) -> Option<SystemLibInfo> {
    use std::process::Command;

    let base_packages: Vec<&str> = packages
        .iter()
        .map(|p| p.split(">=").next().unwrap_or(p).trim())
        .collect();

    // Get prefix
    let prefix_output = Command::new("pkg-config")
        .args(["--variable=prefix"])
        .args(&base_packages)
        .output()
        .ok()?;

    if !prefix_output.status.success() {
        return None;
    }

    let prefix = String::from_utf8_lossy(&prefix_output.stdout)
        .trim()
        .to_string();

    if prefix.is_empty() {
        return None;
    }

    // Get cflags to extract include dirs
    let cflags_output = Command::new("pkg-config")
        .args(["--cflags"])
        .args(&base_packages)
        .output()
        .ok()?;

    let cflags_str = String::from_utf8_lossy(&cflags_output.stdout);
    let include_dirs: Vec<String> = cflags_str
        .split_whitespace()
        .filter_map(|f| f.strip_prefix("-I"))
        .map(|p| {
            // Try to make path relative to prefix
            p.strip_prefix(&prefix).map_or_else(|| p.to_string(), |rel| rel.trim_start_matches('/').to_string())
        })
        .collect();

    // Get libs
    let libs_output = Command::new("pkg-config")
        .args(["--libs"])
        .args(&base_packages)
        .output()
        .ok()?;

    let libs_str = String::from_utf8_lossy(&libs_output.stdout);
    let mut libs = Vec::new();
    let mut lib_dirs = Vec::new();

    for flag in libs_str.split_whitespace() {
        if let Some(lib) = flag.strip_prefix("-l") {
            libs.push(lib.to_string());
        } else if let Some(dir) = flag.strip_prefix("-L") {
            let rel_dir = dir.strip_prefix(&prefix).map_or_else(|| dir.to_string(), |rel| rel.trim_start_matches('/').to_string());
            lib_dirs.push(rel_dir);
        }
    }

    Some(SystemLibInfo {
        name: (*base_packages.first()?).to_string(),
        packages: packages.to_vec(),
        prefix: Some(prefix),
        include_dirs,
        lib_dirs,
        libs,
    })
}

