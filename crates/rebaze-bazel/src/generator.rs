//! Gradle generation uses rule schemas; project values never become source code.

use std::collections::BTreeSet;

use crate::starlark::{
    BazelDep, ExportsFiles, File, Glob, Identifier, JavaLibrary, JavaTest, Load, MavenInstall,
    Module, Reference, RenderResult, UseExtension, UseRepo,
};

/// Represents a generated Bazel file.
pub struct BazelFile {
    pub path: String,
    pub content: String,
}

pub fn generate_module_bazel(project: &rebaze_gradle::GradleProject) -> RenderResult<String> {
    let mut file = File::new();
    file.docstring(&format!(
        "Bazel module for {} - generated by rebaze.",
        project.name
    ))?;
    file.statement(&Module {
        name: project.name.replace('-', "_"),
        version: "0.1.0".into(),
    })?;

    let has_kotlin = project
        .plugins
        .iter()
        .any(|plugin| plugin.id.contains("kotlin"));
    let has_java = project
        .plugins
        .iter()
        .any(|plugin| plugin.id.contains("java"));
    if has_kotlin {
        file.statement(&BazelDep {
            name: "rules_kotlin".into(),
            version: "2.1.0".into(),
        })?;
    }
    if has_java || has_kotlin || !project.subprojects.is_empty() {
        file.statement(&BazelDep {
            name: "rules_java".into(),
            version: "8.6.4".into(),
        })?;
    }
    if !project.dependencies.is_empty() {
        file.statement(&BazelDep {
            name: "rules_jvm_external".into(),
            version: "6.6".into(),
        })?;
        file.assign(
            &Identifier::new("maven")?,
            &UseExtension("@rules_jvm_external//:extensions.bzl", "maven"),
        )?;
        let artifacts = project
            .dependencies
            .iter()
            .filter(|dependency| !dependency.version.is_empty())
            .map(|dependency| {
                format!(
                    "{}:{}:{}",
                    dependency.group, dependency.artifact, dependency.version
                )
            })
            .collect::<BTreeSet<_>>()
            .into_iter()
            .collect();
        file.statement(&MavenInstall {
            artifacts,
            repositories: vec!["https://repo.maven.apache.org/maven2".into()],
        })?;
        file.statement(&UseRepo {
            extension: Reference::new("maven")?,
            repositories: vec!["maven".into()],
        })?;
    }
    file.render()
}

pub fn generate_root_build(project: &rebaze_gradle::GradleProject) -> RenderResult<String> {
    let mut file = File::new();
    file.comment(&format!(
        "Root BUILD file for {} - generated by rebaze",
        project.name
    ));
    file.statement(&ExportsFiles(vec!["MODULE.bazel".into()]))?;
    file.render()
}

pub fn generate_subproject_build(
    _project: &rebaze_gradle::GradleProject,
    subproject: &str,
) -> RenderResult<String> {
    let target_name = subproject
        .split(':')
        .next_back()
        .unwrap_or(subproject)
        .replace('-', "_");
    let mut file = File::new();
    file.comment(&format!(
        "BUILD file for {subproject} - generated by rebaze"
    ));
    file.load(Load {
        bzl: "@rules_java//java:defs.bzl".into(),
        items: ["java_library".into(), "java_test".into()].into(),
    })?;
    file.comment(
        "TODO: Map library and test dependencies; select the test class before building tests.",
    );
    file.statement(&JavaLibrary {
        name: target_name.clone(),
        srcs: Glob::new_allow_empty(vec!["src/main/java/**/*.java".into()]),
        resources: Glob::new_allow_empty(vec!["src/main/resources/**".into()]),
        visibility: vec!["//visibility:public".into()],
        deps: vec![],
    })?;
    file.statement(&JavaTest {
        name: format!("{target_name}_test"),
        srcs: Glob::new_allow_empty(vec!["src/test/java/**/*.java".into()]),
        test_class: "TODO".into(),
        deps: vec![format!(":{target_name}")],
    })?;
    file.render()
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    #[test]
    fn kotlin_maven_dependencies_declare_their_extension_module() {
        for source in [
            "dependencies {\n implementation(\"org.example:lib:1.0\")\n}",
            "plugins {\n kotlin(\"jvm\")\n}\ndependencies {\n implementation(\"org.example:lib:1.0\")\n}",
        ] {
            let temp = tempfile::tempdir().unwrap();
            std::fs::write(temp.path().join("build.gradle.kts"), source).unwrap();
            std::fs::write(
                temp.path().join("settings.gradle.kts"),
                "rootProject.name = \"example\"",
            )
            .unwrap();
            let project = rebaze_gradle::parse(temp.path()).unwrap();
            let module = generate_module_bazel(&project).unwrap();
            assert!(module.contains("name = \"rules_jvm_external\""));
            assert!(module.contains("maven.install("));
            assert!(module.contains("https://repo.maven.apache.org/maven2"));
            let build = generate_subproject_build(&project, "app").unwrap();
            assert!(build.contains("\"java_library\""));
            assert!(build.contains("\"java_test\""));
        }
    }
}
